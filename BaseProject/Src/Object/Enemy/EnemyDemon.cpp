EnemyDemon::EnemyDemon(void)
{
}

EnemyDemon::~EnemyDemon(void)
{
}

// =============================================================================
// デーモンの固有パラメータ設定（教材第24, 27, 32章参照）
// =============================================================================
void EnemyDemon::SetParam(void)
{
	scales_ = { 0.7f, 0.7f, 0.7f }; // モデルのスケール（少し大きめ）
	speed_ = 5.0f;                  // 移動スピード
	hp_ = 3;                        // 体力初期値（パンチ3発分）
	spawnRange_ = 1.0f;             // 出現範囲倍率
	collisionRadius_ = 50.0f;       // 衝突判定球体の半径（教材第32章）
	cntAttack_ = 0;                 // 攻撃間隔カウンタ
}

// =============================================================================
// 通常待機状態の更新処理（オーバーライド）
// 常にプレイヤーを向きながら直進移動する
// =============================================================================
void EnemyDemon::UpdateStandby(void)
{
	// 常にプレイヤーの方向を向く
	LookPlayer();
	// プレイヤーに向かって前進移動（体当たり攻撃）
	Move();
}
