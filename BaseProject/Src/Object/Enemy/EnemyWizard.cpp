#include "EnemyWizard.h"

// =============================================================================
// コンストラクタ / デストラクタ
// =============================================================================
EnemyWizard::EnemyWizard(void)
{
}

EnemyWizard::~EnemyWizard(void)
{
}

// =============================================================================
// ウィザードの固有パラメータ設定（教材第26, 27, 30, 32章参照）
// =============================================================================
void EnemyWizard::SetParam(void)
{
	scales_ = { 0.5f, 0.5f, 0.5f }; // モデルのスケール
	speed_ = 0.0f;                  // 移動速度（ウィザードは移動しない：教材第27章）
	hp_ = 2;                        // 体力初期値
	spawnRange_ = 0.8f;             // 出現範囲倍率
	collisionRadius_ = 40.0f;       // 衝突判定球体の半径（教材第32章）
	cntAttack_ = 0;                 // 攻撃間隔カウンタ
}

// =============================================================================
// 通常待機状態の更新処理（オーバーライド）
// プレイヤーの方向を向き続け、一定フレームごとに攻撃ステートへ遷移
// =============================================================================
void EnemyWizard::UpdateStandby(void)
{
	// 常にプレイヤーの方向を向く
	LookPlayer();

	// 攻撃間隔カウントアップ
	cntAttack_++;
	if (cntAttack_ >= TERM_ATTACK)
	{
		cntAttack_ = 0; // カウンタリセット
		ChangeState(STATE::ATTACK);
	}
}
